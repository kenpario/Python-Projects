#Strings
first_name = "Tibi"

print(f"Hello, {first_name}!")

#Integers
age = 25

print(f"{first_name} is {age} years old.")

#Floats
price = 15.45

print(f"The price is ${price}.")

#Boolean
if age >= 50:
    is_elder = True
else:
    is_elder = False

if is_elder:
    print(f"{first_name} is an elder")
else:
    print(f"{first_name} is not an elder")
